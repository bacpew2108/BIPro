import AppKit
import DAXEngine
import Foundation
import PBIXKit
import Testing
@testable import BIPro

@Suite("v1.2 (T014) — Power BI Desktop 2.159 VM Gate PBIX Generator")
struct V12GatePBIXTests {
    private var nhom6: URL? {
        let fm = FileManager.default
        if let env = ProcessInfo.processInfo.environment["BIPRO_NHOM6"], fm.fileExists(atPath: env) {
            return URL(fileURLWithPath: env)
        }
        let home = fm.homeDirectoryForCurrentUser
        for rel in [
            "Downloads/Nhom6_Dashboard_chiase.pbix",
            "Downloads/Nhom6_Dashboard.pbix",
            "Downloads/bipro-golden/Nhom6_work.pbix",
        ] {
            let url = home.appendingPathComponent(rel)
            if fm.fileExists(atPath: url.path) { return url }
        }
        return nil
    }

    @MainActor
    @Test("Generate build/v12-out/bipro-v12-gate.pbix with Paste cross-page, Format Painter, Quick Measure, Mark as Date Table & RLS Role")
    func generateV12GatePBIX() async throws {
        guard ProcessInfo.processInfo.environment["BIPRO_V12_GATE"] == "1" else { return }
        let savedLast = UserDefaults.standard.string(forKey: "lastWorkspace")
        defer {
            if let savedLast { UserDefaults.standard.set(savedLast, forKey: "lastWorkspace") }
            else { UserDefaults.standard.removeObject(forKey: "lastWorkspace") }
        }
        let source = try #require(nhom6, "Nhom6 PBIX not found in ~/Downloads")
        let stamp = try FileStamp.of(source)
        let workspace = try Workspace(data: Data(contentsOf: source))
        let state = DocumentState(workspace: workspace, fileName: source.lastPathComponent, fileURL: source)
        state.mode = .report
        state.editMode = true

        // 1. Tạo trang mới "v1.2 Gate"
        let pageID = try #require(state.layout.addPage())
        #expect(state.layout.renamePage(pageID, to: "v1.2 Gate") == nil)
        state.layout.showPage(pageID)
        state.pageID = pageID

        // 2. Tạo Quick Measure (% of grand total + YTD)
        let qmGen = QuickMeasureTemplate.percentOfGrandTotal.generate(
            baseMeasure: "Total_Clients",
            categoryTable: "Dim_District",
            categoryColumn: "region"
        )
        let qm = NewMeasure(table: "Dim_Client", name: "V12_Clients_Pct_Total",
                            expression: qmGen.expression, formatString: "0.0%",
                            dataType: ModelMetadata.DataType.double.rawValue)
        #expect(state.modelEditor.apply(.addMeasure(qm)) == nil)

        // 3. Ghi vai trò RLS chuẩn Desktop 2.159 (`[Role]` + `[TablePermission]`)
        let midwestRole = ModelMetadata.RoleDefinition(
            name: "V12_Midwest_Viewer",
            description: "RLS role generated by BI Pro v1.2",
            modelPermission: 2,
            tablePermissions: [
                ModelMetadata.TablePermission(tableName: "Dim_District", filterExpression: #"Dim_District[region] = "Midwest""#),
            ]
        )
        #expect(state.saveRLSRoles([(previous: nil, role: midwestRole)]) == nil)

        // 4. Chèn 2 visual trên trang v1.2 Gate, áp Format Painter từ v1 sang v2, và Copy/Paste sang v3
        let region = FieldRef(kind: .column, entity: "Dim_District", property: "region", family: .text)
        let clients = FieldRef(kind: .measure, entity: "Dim_Client", property: "Total_Clients")
        let pctRef = FieldRef(kind: .measure, entity: "Dim_Client", property: "V12_Clients_Pct_Total")

        let v1 = try #require(state.layout.insertVisual(type: "clusteredColumnChart", visibleRect: CGRect(x: 20, y: 20, width: 580, height: 340)))
        state.layout.apply(frames: [v1: Frame(x: 20, y: 20, width: 580, height: 340)])
        #expect(state.layout.addField(region, to: "Category", visual: v1) == nil)
        #expect(state.layout.addField(clients, to: "Y", visual: v1) == nil)
        #expect(state.layout.setFormat(.bool(true), scope: .container, object: "title", property: "show", visual: v1) == nil)
        #expect(state.layout.setFormat(.text("BI Pro v1.2 Gate — Clients by Region"), scope: .container, object: "title", property: "text", visual: v1) == nil)
        #expect(state.layout.setFormat(.bool(true), scope: .container, object: "border", property: "show", visual: v1) == nil)
        #expect(state.layout.setFormat(.color(.hex("#118DFF")), scope: .container, object: "border", property: "color", visual: v1) == nil)

        let v2 = try #require(state.layout.insertVisual(type: "tableEx", visibleRect: CGRect(x: 620, y: 20, width: 620, height: 340)))
        state.layout.apply(frames: [v2: Frame(x: 620, y: 20, width: 620, height: 340)])
        #expect(state.layout.addField(region, to: "Values", visual: v2) == nil)
        #expect(state.layout.addField(clients, to: "Values", visual: v2) == nil)
        #expect(state.layout.addField(pctRef, to: "Values", visual: v2) == nil)

        // Format Painter v1 -> v2
        state.layout.select(v1)
        state.layout.beginFormatPainter()
        #expect(state.layout.applyFormatPainter(to: v2))

        // Copy & Paste 1 Card visual
        let vCard = try #require(state.layout.insertVisual(type: "card", visibleRect: CGRect(x: 20, y: 390, width: 300, height: 150)))
        state.layout.apply(frames: [vCard: Frame(x: 20, y: 390, width: 300, height: 150)])
        #expect(state.layout.addField(pctRef, to: "Values", visual: vCard) == nil)
        state.layout.select(vCard)
        state.layout.copy()
        let pasted = state.layout.paste()
        #expect(pasted.count == 1)
        state.layout.apply(frames: [pasted[0]: Frame(x: 350, y: 390, width: 300, height: 150)])

        // 5. Lưu ra `build/v12-out/bipro-v12-gate.pbix` và xác minh round-trip
        let repoRoot = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .deletingLastPathComponent()
        let outDir = repoRoot.appendingPathComponent("build/v12-out", isDirectory: true)
        try FileManager.default.createDirectory(at: outDir, withIntermediateDirectories: true)
        let outURL = outDir.appendingPathComponent("bipro-v12-gate.pbix")
        try? FileManager.default.removeItem(at: outURL)
        _ = try DocumentSaver.save(editor: state.layout, source: source, to: outURL, expectedStamp: stamp)

        let reopened = try Workspace(data: Data(contentsOf: outURL))
        let gatePage = try #require(reopened.report.pages.first { $0.displayName == "v1.2 Gate" })
        #expect(gatePage.visuals.count == 4)
        #expect(reopened.measure(table: "Dim_Client", name: "V12_Clients_Pct_Total") != nil)
        #expect(reopened.metadata?.roleDefinitions.contains { $0.name == "V12_Midwest_Viewer" } == true)
    }
}
